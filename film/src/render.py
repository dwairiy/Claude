def render(lang, audio):
    out_dir = FILM / "out"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"sakina_the_first_word_animatic_{lang.upper()}.mp4"
    ff = subprocess.Popen(["ffmpeg", "-loglevel", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}",
                           "-r", str(FPS), "-i", "-", "-i", str(audio), "-map", "0:v", "-map", "1:a",
                           "-c:v", "libx264", "-preset", "medium", "-crf", "17", "-pix_fmt", "yuv420p",
                           "-c:a", "aac", "-b:a", "320k", "-t", str(DUR), "-movflags", "+faststart", str(out)],
                          stdin=subprocess.PIPE)
    used = {}
    for i in range(NF):
        t = i / FPS
        s = next(x for x in SHOTS.values() if x["t0"] <= t + 1e-6 < x["t1"] or (x["n"] == 23 and t >= x["t0"]))
        n, tl = s["n"], t - s["t0"]
        clip = clip_frames(n, s["t1"] - s["t0"])
        if clip is not None:
            frame, source = clip[min(int(tl * FPS), len(clip) - 1)].astype(np.float32) / 255, "CLIP"
        elif n == 23:
            frame, source = render_endcard(t, tl, lang), "CG"
        elif n in PROCEDURAL:
            frame, source = PROCEDURAL[n](t, tl), "RENDER"
        else:
            frame, source = render_board(n, t, tl), "BOARD"
        used[n] = source
        img = overlays(to_img(frame), t, lang, n, source)
        ff.stdin.write(np.asarray(img.convert("RGB"), dtype=np.uint8).tobytes())
        if i % 125 == 0:
            print(f"  {lang} {t:5.1f}s shot {n:02d} {source}")
    ff.stdin.close()
    ff.wait()
    return out, used


