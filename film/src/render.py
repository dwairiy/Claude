# ---------------------------------------------------------------- clips (AI or real footage)
@lru_cache(None)
def clip_frames(n, dur):
    path = FILM / "clips" / f"shot_{n:02d}.mp4"
    if not path.exists():
        return None
    nfr = max(1, round(dur * FPS))
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", str(path), "-vf",
                          f"fps={FPS},scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H}",
                          "-frames:v", str(nfr), "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], capture_output=True, check=True).stdout
    fr = np.frombuffer(raw, np.uint8).reshape(-1, H, W, 3)
    return fr


