# ---------------------------------------------------------------- utilities
@lru_cache(None)
def font(name, size):
    return ImageFont.truetype(str(FONTS / name), size)


def to_np(img):
    return np.asarray(img.convert("RGB"), dtype=np.float32) / 255


def to_img(a):
    return Image.fromarray((np.clip(a, 0, 1) * 255).astype(np.uint8))


def grad(top, bottom, h=H, w=W):
    t = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]
    return np.broadcast_to((np.array(top) * (1 - t) + np.array(bottom) * t) / 255, (h, w, 3)).copy()


def ease_out(x):
    x = np.clip(x, 0, 1)
    return 1 - (1 - x) ** 3


def ease_io(x):
    x = np.clip(x, 0, 1)
    return x * x * (3 - 2 * x)


def zoom(a, s):
    """Centre zoom of a frame by factor s >= 1 (slow push-ins)."""
    if s <= 1.0001:
        return a
    img = to_img(a)
    cw, ch = W / s, H / s
    box = ((W - cw) / 2, (H - ch) / 2, (W + cw) / 2, (H + ch) / 2)
    return to_np(img.resize((W, H), Image.BICUBIC, box=box))


def text(draw, xy, s, fnt, fill, anchor="la", rtl=False, **kw):
    if rtl:
        draw.text(xy, s, font=fnt, fill=fill, anchor=anchor, direction="rtl", language="ar", **kw)
    else:
        draw.text(xy, s, font=fnt, fill=fill, anchor=anchor, **kw)


def wrap(s, fnt, width):
    words, lines, cur = s.split(), [], ""
    for w_ in words:
        trial = (cur + " " + w_).strip()
        if fnt.getlength(trial) > width and cur:
            lines.append(cur)
            cur = w_
        else:
            cur = trial
    return lines + [cur]


@lru_cache(None)
def paper():
    base = grad((238, 228, 208), (226, 212, 186))
    fib = ndimage.gaussian_filter(rng.standard_normal((H, W)).astype(np.float32), (0.6, 6))
    grain = rng.standard_normal((H, W)).astype(np.float32) * 0.012
    return np.clip(base * (1 + 0.025 * fib[..., None] + grain[..., None]), 0, 1)


# ---------------------------------------------------------------- shot list
def load_shots():
    shots = []
    for r in csv.DictReader(open(ROOT / "production" / "shot_list.csv", encoding="utf-8")):
        if not r["shot"].isdigit():
            continue
        r["n"] = int(r["shot"])
        r["t0"] = float(r["tc_in"].split(":")[1]) + 60 * int(r["tc_in"].split(":")[0])
        r["t1"] = float(r["tc_out"].split(":")[1]) + 60 * int(r["tc_out"].split(":")[0])
        shots.append(r)
    return shots


def method_tag(m):
    for k in ("COMP", "CG", "AI", "LIVE"):
        if k in m:
            return k
    return "LIVE"


