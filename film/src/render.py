@lru_cache(None)
def inkwell_bg():
    img = to_img(paper())
    d = ImageDraw.Draw(img, "RGBA")
    # qalam (reed pen) lying diagonally, with a soft shadow
    pen = [(1180, 880), (1720, 260), (1745, 282), (1205, 902)]
    sh = Image.new("L", (W, H), 0)
    ImageDraw.Draw(sh).polygon([(x + 18, y + 22) for x, y in pen], fill=110)
    img.paste((40, 30, 20), (0, 0), sh.filter(ImageFilter.GaussianBlur(14)))
    d.polygon(pen, fill=(176, 132, 74))
    for k in range(1, 5):  # bamboo nodes
        x0, y0 = 1180 + k * 108, 880 - k * 124
        d.line([(x0, y0), (x0 + 25, y0 + 22)], fill=(120, 84, 40), width=6)
    d.polygon([(1180, 880), (1205, 902), (1150, 950)], fill=(30, 22, 14))  # cut nib, inked
    # inkwell shadow and glass rim
    cx, cy = 820, 540
    sh = Image.new("L", (W, H), 0)
    ImageDraw.Draw(sh).ellipse((cx - 330 + 30, cy - 330 + 40, cx + 330 + 30, cy + 330 + 40), fill=150)
    img.paste((40, 30, 20), (0, 0), sh.filter(ImageFilter.GaussianBlur(30)))
    d.ellipse((cx - 330, cy - 330, cx + 330, cy + 330), fill=(212, 214, 210))
    d.ellipse((cx - 300, cy - 300, cx + 300, cy + 300), fill=(150, 156, 158))
    return to_np(img), (cx, cy)


def render_inkwell(t, tl):
    bg, (cx, cy) = inkwell_bg()
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    dx, dy = xx - cx, yy - cy
    r = np.sqrt(dx * dx + dy * dy)
    R = 278
    inside = r < R
    slope = np.zeros_like(r)
    for k in range(int(t / 0.25) + 1):  # one ripple per bass eighth
        age = t - k * 0.25
        if age < 0 or age > 1.6:
            continue
        amp = (1.0 if k % 2 == 0 else 0.55) * np.exp(-age * 2.6)
        front = 40 + age * 420
        ph = (r - front) / 26
        slope += amp * np.cos(ph * 2 * np.pi) * np.exp(-((r - front + 60) / 120) ** 2)
    light = (dx * -0.6 + dy * -0.8) / np.maximum(r, 1)
    spec = np.clip(slope * light, 0, None) ** 1.4 * 0.55
    gloss = 0.35 * np.exp(-(((xx - cx + 110) / 70) ** 2 + ((yy - cy + 120) / 45) ** 2))
    ink = 0.03 + spec + gloss
    out = bg.copy()
    edge = np.clip((R - r) / 3, 0, 1)[..., None]
    out = out * (1 - edge) + edge * np.stack([ink * 0.95, ink * 0.97, ink * 1.05], -1)
    return zoom(out, 1 + 0.02 * tl / 2)


